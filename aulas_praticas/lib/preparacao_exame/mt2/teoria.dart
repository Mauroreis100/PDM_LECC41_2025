// 5. O que é o SOLID?
R: SOLID é um acrónimo que representa cinco princípios de design de software que visam tornar o código mais compreensível, flexível e fácil de manter. Os princípios são:
   - S: Single Responsibility Principle (Princípio da Responsabilidade Única)
   - O: Open/Closed Principle (Princípio Aberto/Fechado)
   - L: Liskov Substitution Principle (Princípio da Substituição de Liskov)
   - I: Interface Segregation Principle (Princípio da Segregação de Interfaces)
   - D: Dependency Inversion Principle (Princípio da Inversão de Dependências)


// 6. O que é o DRY?
R: DRY é um acrónimo que significa "Don't Repeat Yourself" (Não se Repita). 
É um princípio de desenvolvimento de software que enfatiza a importância de evitar 
a duplicação de código. A ideia é que cada pedaço de conhecimento ou lógica 
deve ter uma única representação no código, o que facilita a manutenção, 
reduz erros e melhora a legibilidade. Quando o código é repetido, qualquer alteração requer modificações em vários locais, aumentando o risco de inconsistências e bugs.

// 7. O que é o KISS?
R: KISS é um acrónimo que significa "Keep It Simple, Stupid" (Mantenha Simples, Estúpido). É um princípio de design de software que enfatiza a simplicidade e a clareza no desenvolvimento. A ideia é que sistemas complexos são mais difíceis de entender, manter e depurar. Portanto, soluções simples são preferíveis, pois são mais fáceis de implementar e menos propensas a erros. O KISS incentiva os desenvolvedores a evitar complicações desnecessárias e a focar em soluções diretas e eficazes.
// 8. O que é o YAGNI?
R: YAGNI é um acrónimo que significa "You Aren't Gonna Need It" (Você Não Vai Precisar Disso). É um princípio de desenvolvimento ágil que sugere que os desenvolvedores não devem adicionar funcionalidades ou complexidade ao código até que sejam realmente necessárias. A ideia é evitar o excesso de trabalho e a implementação de recursos que podem nunca ser utilizados, o que ajuda a manter o código mais simples e fácil de manter. YAGNI incentiva a focar nas necessidades atuais do projeto, em vez de antecipar requisitos futuros que podem nunca se concretizar.
// 9. O que é o TDD?
R: TDD, ou Test-Driven Development (Desenvolvimento Orientado a Testes), é uma prática de desenvolvimento de software onde os testes são escritos antes do código funcional. O processo envolve três etapas principais: escrever um teste que falha (porque a funcionalidade ainda não foi implementada), escrever o código mínimo necessário para passar no teste e, finalmente, refatorar o código para melhorar sua qualidade sem alterar seu comportamento. O TDD ajuda a garantir que o código atenda aos requisitos desde o início, melhora a cobertura de testes e facilita a manutenção do software.


